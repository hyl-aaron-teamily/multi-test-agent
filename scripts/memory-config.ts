// W3-5 §8.9 / E2: the memory service's gateway config (.docker/memory-core/tdai-gateway.yaml), from .env. The
// extraction model defaults to ours (MIDSCENE_MODEL_*: one model service, its usage counted apart, V15).
// After deploy/global-images/start-memory-core.sh of TencentDB Agent Memory (MIT): the same keys, standalone,
// sqlite, skill module on, no embedding. The file holds an API key: .docker/ is not in git.
//   MEMORY_LLM_BASE_URL / MEMORY_LLM_API_KEY / MEMORY_LLM_MODEL   (default: MIDSCENE_MODEL_BASE_URL / _API_KEY / _NAME)
//   MEMORY_PROMPT_MODE  code (default) | chat
import 'dotenv/config';
import { randomBytes } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const q = (s: string | undefined) => JSON.stringify(s ?? '');

/** Pure: the gateway config text. */
export function gatewayConfig(env: Record<string, string | undefined>): string {
  const base = env.MEMORY_LLM_BASE_URL ?? env.MIDSCENE_MODEL_BASE_URL;
  const key = env.MEMORY_LLM_API_KEY ?? env.MIDSCENE_MODEL_API_KEY;
  const model = env.MEMORY_LLM_MODEL ?? env.MIDSCENE_MODEL_NAME;
  return `# Generated by scripts/memory-config.ts from .env — do not edit; not in git.
deployMode: standalone
stateBackend: local
server:
  port: 8420
  host: 0.0.0.0
data:
  baseDir: /data/tdai-memory
llm:
  baseUrl: ${q(base)}
  apiKey: ${q(key)}
  model: ${q(model)}
  maxTokens: 32000
  timeoutMs: 300000
memory:
  promptMode: ${env.MEMORY_PROMPT_MODE === 'chat' ? 'chat' : 'code'}
  capture: { enabled: true }
  extraction:
    enabled: true
    enableDedup: true
    maxMemoriesPerSession: 20
  pipeline:
    everyNConversations: 5
    enableWarmup: true
    l1IdleTimeoutSeconds: 600
    l2DelayAfterL1Seconds: 90
    l2MinIntervalSeconds: 900
    l2MaxIntervalSeconds: 3600
  recall:
    enabled: true
    maxResults: 5
    scoreThreshold: 0.3
    strategy: hybrid
    timeoutMs: 5000
  storeBackend: sqlite
  embedding:
    provider: none
skill:
  enabled: true
  routing:
    mode: bm25
    searchTopK: 20
  extraction:
    enabled: false
  resources:
    maxResourceSizeBytes: 5000000
`;
}

export const GATEWAY_CONFIG = resolve('.docker/memory-core/tdai-gateway.yaml');

export function writeGatewayConfig(file = GATEWAY_CONFIG): string {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, gatewayConfig(process.env));
  return file;
}

export const ADMIN_KEY_FILE = resolve('.docker/memory-core/admin-key');
export const IDS_FILE = resolve('.docker/memory-core/ids.json');

async function post(base: string, path: string, body: unknown, key?: string): Promise<{ status: number; json: any }> {
  const r = await fetch(`${base}${path}`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-tdai-service-id': 'default', ...(key ? { authorization: `Bearer ${key}`, 'x-tdai-user-key': key } : {}) }, body: JSON.stringify(body) });
  return { status: r.status, json: await r.json().catch(() => ({})) };
}

/** First start of a fresh memory volume: the admin user with our own random key (kept in
 *  .docker/memory-core/admin-key: the v3 Bearer), then the team and the three agents (explore / plan-run /
 *  plan-author) whose ids the service makes (kept in ids.json; the client maps our names to them). */
export async function ensureAdminKey(base = process.env.MEMORY_CORE_URL ?? 'http://localhost:8420', waitMs = 60_000): Promise<string> {
  const until = Date.now() + waitMs;
  while (!(await fetch(`${base}/health`).then((r) => r.ok, () => false))) {
    if (Date.now() > until) throw new Error(`memory-core not healthy at ${base}`);
    await new Promise((r) => setTimeout(r, 2000));
  }
  const { existsSync, readFileSync } = await import('node:fs');
  const out: string[] = [];
  let key = existsSync(ADMIN_KEY_FILE) ? readFileSync(ADMIN_KEY_FILE, 'utf8').trim() : '';
  if (!key) key = `sk-mem-${randomBytes(24).toString('base64').replace(/[^A-Za-z0-9]/g, '').slice(0, 32)}`;
  const init = await post(base, '/v3/internal/meta/user/init-admin', { username: 'admin', user_key: key });
  if (init.status === 200) {
    mkdirSync(dirname(ADMIN_KEY_FILE), { recursive: true });
    writeFileSync(ADMIN_KEY_FILE, key);
    out.push('admin key created');
  } else if (init.status === 409) {
    if (!existsSync(ADMIN_KEY_FILE)) throw new Error('admin user exists but .docker/memory-core/admin-key is missing: `docker compose down -v` drops the memory volume, then start again');
    out.push('admin key exists');
  } else throw new Error(`init-admin: HTTP ${init.status} ${JSON.stringify(init.json).slice(0, 200)}`);
  if (existsSync(IDS_FILE)) return [...out, 'team / agents registered'].join('; ');
  const who = await post(base, '/v3/meta/auth/verify', { user_key: key }, key);
  const user = who.json?.data?.user_id ?? who.json?.data?.user?.user_id;
  if (!user) throw new Error(`auth/verify gave no user_id: ${JSON.stringify(who.json).slice(0, 200)}`);
  const team = await post(base, '/v3/meta/team/create', { name: 'multi-test-agent', owner_user_id: user, description: 'autotest: Teamily black-box testing' }, key);
  const teamId = team.json?.data?.team_id;
  if (!teamId) throw new Error(`team/create: ${JSON.stringify(team.json).slice(0, 200)}`);
  const agents: Record<string, string> = {};
  for (const name of ['explore', 'plan-run', 'plan-author']) {
    const a = await post(base, '/v3/meta/agent/create', { team_id: teamId, owner_user_id: user, name, description: `autotest ${name}` }, key);
    if (!a.json?.data?.agent_id) throw new Error(`agent/create ${name}: ${JSON.stringify(a.json).slice(0, 200)}`);
    agents[name] = a.json.data.agent_id;
  }
  writeFileSync(IDS_FILE, JSON.stringify({ user, team: teamId, agents }, null, 2));
  return [...out, `registered team ${teamId} and agents ${Object.keys(agents).join(', ')}`].join('; ');
}

if (process.argv[1] && /memory-config\.ts$/.test(process.argv[1].replace(/\\/g, '/'))) {
  console.log(`wrote ${writeGatewayConfig()}`);
  if (process.argv.includes('--init')) ensureAdminKey().then((m) => console.log(m), (e) => (console.error((e as Error).message), process.exit(1)));
}
